def checkVersion():
    import urllib.request

    import originpro as op #type: ignore
    import os

    def get_installed_version():
        """
        Determines the Origin User Files Folder (UFF) and reads:
            <UFF>/PXRD_versionTag.txt

        Returns:
            (installed_version, ignore_version, version_file)
        """

        # Determine UFF using LabTalk
        op.lt_exec('string __uff$ = %Y;')
        uff_path = op.get_lt_str('__uff$')

        version_file = os.path.join(uff_path, "PXRD_versionTag.txt")

        if not os.path.exists(version_file):
            return (None, None, None)

        try:
            with open(version_file, "r", encoding="utf-8") as f:
                lines = f.read().splitlines()

            # No lines? Treat as missing
            if not lines:
                return (None, None, version_file)

            installed_version = lines[0].strip() if lines[0].strip() else None

            ignore_version = None
            if len(lines) >= 2:
                second = lines[1].strip()
                if second.startswith("ignore "):
                    ignore_version = second.split(" ", 1)[1].strip()

            return (installed_version, ignore_version, version_file)

        except Exception:
            return (None, None, None)



    def get_latest_version():
        url = "https://raw.githubusercontent.com/errthumt/Origin-PXRD/main/build/PXRD_versionTag.txt"
        try:
            with urllib.request.urlopen(url, timeout=5) as response:
                text = response.read().decode("utf-8")
                lines = text.splitlines()
                return lines[0].strip() if lines else None
        except Exception as e:
            print(e)
            return None


    def notify_if_outdated(local_version,ignore_version,version_file):
        latest = get_latest_version()
        if latest is None:
            return
        #print(f'latest: {latest}')
        #print(f'ignore: {ignore_version}')

        if latest != local_version and latest != ignore_version:
            lt_cmd=f'''
                t=4;
                type -y 
                "NEW UPDATE AVAILABLE\n
                A new version of Origin-PXRD is available:\n
                Latest Version: {latest}\n
                Your Version: {local_version}\n
                Would you like to open the most recent release in your browser?\n
                (Press \"Cancel\" to ignore until next release.)"
                '''
            op.lt_exec(lt_cmd)
            t = op.lt_int('t')
            if t==1:
                import webbrowser
                webbrowser.open("https://errthumt.github.io/Origin-PXRD/release_notes.html")
                return
            elif t == 4:
                # User clicked Cancel → ignore this specific version until next release
                try:
                    # Read existing file (if any)
                    lines = []
                    if os.path.isfile(version_file):
                        with open(version_file, "r", encoding="utf-8") as f:
                            lines = f.read().splitlines()

                    # Ensure at least one line exists (local version)
                    if not lines:
                        lines = [local_version]

                    # Overwrite or append ignore line
                    ignore_line = f"ignore {latest}"
                    if len(lines) >= 2:
                        lines[1] = ignore_line
                        if len(lines) == 2:
                            lines.append('DO NOT EDIT THIS FILE, it is used to check for further updates.')
                        else:
                            lines[2] = 'DO NOT EDIT THIS FILE, it is used to check for further updates.'
                    else:
                        lines.append(ignore_line)
                        lines.append('DO NOT EDIT THIS FILE, it is used to check for further updates.')
                    # Write back
                    with open(version_file, "w", encoding="utf-8") as f:
                        f.write("\n".join(lines) + "\n")

                    print(f"Updated version file to ignore version {latest}")

                except Exception as e:
                    print(f"Error updating version file: {e}")

                return


        return

    # Example usage:
    LOCAL_VERSION, ignore_version, version_file = get_installed_version()
    notify_if_outdated(LOCAL_VERSION,ignore_version, version_file)

def process11ID():
    import re
    import originpro as op #type: ignore
    from pathlib import Path

    _BEAMLINE_WAVELENGTH = 0.11595

    op.lt_exec('dlgPath init:=%X title:="Select sample ID folder (contains xye folder and all metadata files)";')
    root = Path(op.get_lt_str("path$"))

    
    # Meta data file names should match corresponding xye names exactly, before file suffixes.
    # Expected file structure:
    #     TE001\
    #         TE001_heat-00001.tif.metadata
    #         TE001_heat-00002.tif.metadata
    #         ... and so on
    #         xye\
    #             TE001_heat-00001.xye
    #             TE001_heat-00002.xye
    #             ... and so on
    xye_folder = root / "xye"
    metadata_folder = root
    output_folder = root / "xye_withTemp"

    output_folder.mkdir(parents=True, exist_ok=True)

    # Temperature stored in userComment4 in metadata.
    temp_pattern = re.compile(r"^userComment4\s*=\s*(.+)$")

    def extract_temperature(metadata_path):
        """Return the temperature string from a .tif.metadata file."""
        with open(metadata_path, "r", encoding="utf-8") as f:
            for line in f:
                m = temp_pattern.match(line.strip())
                if m:
                    return m.group(1).strip()
        return None


    # Extract temperature from each metadata file and insert it into the first line of xye file.
    # Results are placed in a new folder:
    #     TE001\
    #         TE001_heat-00001.tif.metadata
    #         TE001_heat-00002.tif.metadata
    #         ... and so on
    #         xye\
    #             TE001_heat-00001.xye
    #             TE001_heat-00002.xye
    #             ... ^^^ these files are unchanged
    #         xye_withTemp\
    #             TE001_heat-00001.xye
    #             TE001_heat-00002.xye
    #             ... ^^^ these NEW files have temperature in the first line
    for xye_file in xye_folder.glob("*.xye"):
        base = xye_file.stem  # filename without extension
        metadata_file = metadata_folder / f"{base}.tif.metadata"

        if not metadata_file.exists():
            print(f"WARNING: No metadata for {base}")
            continue

        temperature = extract_temperature(metadata_file)
        if temperature is None:
            print(f"WARNING: No userComment4 entry in {metadata_file}")
            continue

        # Read original .xye
        with open(xye_file, "r", encoding="utf-8") as f:
            lines = f.readlines()

        if not lines:
            print(f"WARNING: Empty file: {xye_file}")
            continue

        # Modify first line
        first_line = lines[0].rstrip("\n")
        new_first_line = f"{first_line}  {temperature}\n"

        # Write new file
        out_path = output_folder / xye_file.name
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(new_first_line)
            f.writelines(lines[1:])

        print(f"Processed: {xye_file.name}  →  Temp={temperature}")
    print("All temperatures added to xye files.")

    # New Workbook
    wb = op.new_book('w',lname="In-Situ Import")
    wks = wb[0]

    # Makes sure Origin is looking for files in new xye_withTemp\ folder
    op.set_lt_str("path$",f"{output_folder}\\")

    # Labtalk to import all .xye files. 
    # Data filter PXRD_11-ID-C_mar2026.oif automatically extracts temperature from first line into "Temp" row.
    import_lt = f'''
    cd path$;
    findFiles ext:=*.xye;
    impFile filtername:="PXRD_11-ID-C_mar2026.oif" location:=user;
    wks.labels(-O)
    '''
    op.lt_exec(import_lt)


    # Configure wavelength at top of this file.
    # Adds wavelength to 2theta column.
    # Q-Space script for Menu plugin expects Wavelength row.
    wks._user_param_row("Wavelength (Å)",True)
    wks.set_label(0,_BEAMLINE_WAVELENGTH,"Wavelength (Å)")

    # Clean up columns
    ncols = wks.cols
    maxInt = 0 # Entire data set will be normalized as one range.
    for col in range(ncols-1,0,-1):
        if col%2==0:
            # All 2theta columns will be identical. Delete all but first one.
            wks.del_col(col)
        else:
            # Set column labels
            wks.set_label(col,'Int','L')
            wks.set_label(col,'AU','U')
            
            # If local maximum is higher than maxInt so far, replace maxInt.
            col_data = wks.to_list(col)
            local_max = max(col_data)
            if local_max > maxInt:
                maxInt = local_max

    # Column labels for 2theta column
    wks.set_label(0,'2θ','L')
    wks.set_label(0,'deg','U')

    ncols = wks.cols        
    for col in range(1,ncols,1):
        # Normalize columns to maxInt = 1
        data = wks.to_list(col)
        norm = [v/maxInt for v in data]
        wks.from_list(col,norm)
        
        # Auto-width resize
        op.lt_exec(f'wcolwidth {col+1} -1')

def anneal(template_mode:str="", argstring:str=""):
    import warnings

    # Axes3D is not included with Origin's native matplotlib, but it is not necessary for this package
    warnings.filterwarnings(
        "ignore",
        message="Unable to import Axes3D",
        category=UserWarning,
        module="matplotlib.projections"
    )
    import matplotlib.pyplot as plt
    import originpro as op #type: ignore
    from itertools import zip_longest
    import sys
    from matplotlib.transforms import ScaledTranslation
    from pathlib import Path

    from cif2xrd.paramUtils import clean_parameters, parse_params, default_params #type:ignore

    from cif2xrd.furnace import Profile, RAMP


    def crop_axes_to_content(ax, l_marg=0, r_marg=0, t_marg=0, b_marg=0, pad=2):
        """
        Remove whitespace by shrinking axis limits to tightly wrap
        all lines, text, and annotations on the Axes.
        pad is in display (pixel) units.
        """
        fig = ax.figure
        fig.canvas.draw()  # ensure all artists have valid extents

        # Collect all bounding boxes in display coords
        bboxes = []

        # Lines, markers, etc.
        for line in ax.lines:
            bboxes.append(line.get_window_extent())

        # Text objects (labels, annotations, etc.)
        for txt in ax.texts:
            bboxes.append(txt.get_window_extent(renderer=fig.canvas.get_renderer()))

        # Collections (e.g., patches, arrows)
        for coll in ax.collections:
            try:
                bboxes.append(coll.get_window_extent(fig.canvas.get_renderer()))
            except Exception:
                pass

        # Merge into a single bounding box
        if not bboxes:
            return  # nothing to crop

        from matplotlib.transforms import Bbox
        full = Bbox.union(bboxes)

        # Add padding in display units
        full = full.expanded((full.width + 2*pad)/full.width,
                            (full.height + 2*pad)/full.height)

        # Convert display → data coordinates
        inv = ax.transData.inverted()
        x0, y0 = inv.transform((full.x0, full.y0))
        x1, y1 = inv.transform((full.x1, full.y1))

        # Apply new limits
        ax.set_xlim(x0-l_marg, x1+r_marg)
        ax.set_ylim(y0-b_marg, y1+t_marg)

    class OriginProfile(Profile):
        def __init__(self, **kwargs):
            if "add_temps" in kwargs:
                try:
                    kwargs["add_temps"] = [int(float(x)) for x in str(kwargs["add_temps"]).split(";") if str(kwargs["add_temps"]).strip() != ""]
                except Exception as e:
                    popup = f"Your 'Add Temps' values could not be read correctly: '{kwargs['add_temps']}'. Exception:\n{e}"
                    op.set_lt_str("popupmsg$", popup)
                    op.lt_exec(fr'type -b popupmsg$;') 
                    kwargs["add_temps"] = []

            super().__init__(**kwargs)


        def plot_to_origin(self):
            fig = self.plot()

            save_file = op.get_lt_str('fname$')

            save_path = Path(save_file)
            save_path.parent.mkdir(parents=True, exist_ok=True)

            fig.savefig(save_file, bbox_inches='tight', pad_inches=0)


    def make_anneal_template():
        wbook = op.load_book('PXRD_anneal_template.ogwu')
        wks = wbook[0]
        op.lt_exec("wks.labels(-O)")

    default_params["anneal"] = {
        "start_temp":      25,   # int
        "min_height":      6.0,   # float
        "add_temps":       "",   # comma‑separated string of numbers, e.g. "500,600,700"
        "ramp_width":      4.0,   # float
        "dwell_width":     6.0,   # float
        "font_size":       30.0,   # float
        "font_family":     "Arial",   # int (0=Arial, 1=Times New Roman, etc.)
        "text_offset":     0.6,   # float
        "line_width":      3.0,   # float
        "l_marg":          1.0,   # float
        "r_marg":          1.0,   # float
        "t_marg":          1.0,   # float
        "b_marg":          1.0    # float
    }


    def make_anneal_plot(cleaned_params=default_params["anneal"]):
        wb = op.find_book()
        wks = wb[0]

        try:
            types = wks.to_list('Type')
            temps = wks.to_list('Temperature')
            notes = wks.to_list('Time/Comment')

            #keys = wks.to_list('Variable')
            #values = wks.to_list('Value')
        except:
            op.lt_exec('type -b "At least one required column not found. It is recommended to use the provided template worksheet.')
            return



        commands = list(zip_longest(types,temps,notes))
        myProf = OriginProfile(**cleaned_params)
        for type, temp, note in commands:
            method = getattr(myProf,type,None)
            if method is not None:
                if type.lower() == RAMP:
                    method(temp,note)
                else:
                    method(note)
        
        myProf.plot_to_origin()
        wks = wb[1]
        wks.activate()
        comment = f'Image Saved to:\n{op.get_lt_str("fname$")}'
        lt_cmd = f'''
            insertimg resize:=1 orng:=col(1)[1];
            col(1)[C]$ = "{comment}";
        '''
        op.lt_exec(lt_cmd)


    # sys.argv[0] = script name
    # sys.argv[1] = first argument from LabTalk
    template_needed = template_mode=="template"

    if template_needed:
        make_anneal_template()
    else:
        params = parse_params(argstring)
        cleaned_params = clean_parameters(params, defaults=default_params["anneal"])
        make_anneal_plot(cleaned_params)


def editFurnace(mode:str):
    import json
    import os
    import originpro as op #type: ignore
    import sys

    op.lt_exec('string __uff$ = %Y;')
    user_files = op.get_lt_str('__uff$').rstrip("\\/")

    def load_user_json():
        """
        Load the user_calibrations.json from the User Files Folder.
        Returns the parsed JSON as a Python dict.
        """

        # Build full path to the JSON file, create if it doesn't exist
        os.makedirs(os.path.join(user_files, "Furnaces"), exist_ok=True)
        json_path = os.path.join(user_files, "Furnaces", "user_calibrations.json")

        if not os.path.exists(json_path):
            with open(json_path, "w") as f:
                json.dump({}, f, indent=4)

        # Load JSON
        with open(json_path, "r") as f:
            data = json.load(f)

        return data

    def load_all_calibrations():
        """
        Load the furnace calibration JSON from the User Files Folder.
        Returns the parsed JSON as a Python dict.
        """
        

        # Build full path to the JSON file
        default_path = os.path.join(user_files, "Furnaces", "default_calibrations.json")
        # Load JSON
        with open(default_path, "r") as f:
            data = json.load(f)

        for furnace in data:
            data[furnace]["source"] = "default"

        user_data = load_user_json()

        for furnace in user_data:
            data[furnace] = user_data[furnace]
            data[furnace]["source"] = "user"

        return data

    def load_furnace(silent=False):
        data = load_all_calibrations()
        wks = op.find_sheet()
        furnace_ID = wks.get_label("Actual Temp",'note1')

        furnace_data = data.get(furnace_ID)
        if not furnace_data:
            op.lt_exec(f'type -b "No calibration data found for furnace ID: \'{furnace_ID}\'. Check for typos or save your changes before reloading.";')
            return

        source = furnace_data["source"]
        set_temps = furnace_data["set"]
        actual_temps = furnace_data["actual"]
        cal_date = furnace_data.get("cal_date", "Unknown")
        two_point = "Y" if furnace_data.get("two_point", False) else "N"

        wks.from_list("Set Temp",set_temps)
        wks.from_list("Actual Temp",actual_temps)
        wks.set_label("Actual Temp",cal_date,"note2")
        wks.set_label("Actual Temp",two_point,"note3")
        
        if not silent:
            op.lt_exec(f'type -b "Loaded {furnace_ID} from {source} calibration data";')

    def save_furnace():
        user_data = load_user_json()

        wks = op.find_sheet()
        furnace_ID = wks.get_label("Actual Temp",'note1')
        set_temps = wks.to_list("Set Temp")
        actual_temps = wks.to_list("Actual Temp")
        cal_date = wks.get_label("Actual Temp","note2")
        two_point = wks.get_label("Actual Temp","note3") == "Y"

        user_data[furnace_ID] = {
            "set": set_temps,
            "actual": actual_temps,
            "cal_date": cal_date,
            "two_point": two_point
        }

        # Build full path to the JSON file
        json_path = os.path.join(user_files, "Furnaces", "user_calibrations.json")
        # Save JSON
        with open(json_path, "w") as f:
            json.dump(user_data, f, indent=4)
        op.lt_exec(f'type -b "Saved {furnace_ID} to user calibration data";')
        load_furnace(silent=True)

    def empty_sheet():
        wbook = op.load_book('PXRD_furnace_template.ogwu')
        wbook.activate()

    dispatch = {
        "load": load_furnace,
        "save": save_furnace,
        "empty": empty_sheet
    }

    if mode in dispatch:
        dispatch[mode]()
    else:
        print(f"Unknown mode: {mode}. Valid modes are: {list(dispatch.keys())}")
